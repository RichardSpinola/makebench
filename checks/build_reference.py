def numbered(node, counter):
    """Give every block of a sample its own id, as the editor does."""
    if isinstance(node, dict):
        if "op" in node:
            counter[0] += 1
            node = {**node, "id": f"b{counter[0]}"}
        return {k: numbered(v, counter) for k, v in node.items()}
    if isinstance(node, list):
        return [numbered(v, counter) for v in node]
    return node


