def python_for(block_type, sample):
    """The Python Makebench generates for one block, taken from the real code generator."""
    project = sample_project()
    statement = (
        sample.get("op")
        not in {
            "literal",
            "list",
            "variable",
            "read",
            "binary",
            "join",
            "file_text",
            "csv_rows",
            "data_find",
            "data_get",
            "data_name",
            "data_count",
            "data_sum",
            "record_field",
            "data_last_id",
        }
        and block_type != "mb_call_value"
    )
    node = sample if statement else {"op": "log", "value": sample}
    node = numbered(node, [0])
    if block_type == "mb_return":
        project.metadata["functions"][0]["body"] = [node]
        code = generate(project).text
        start = code.index("def fn_greet")
        lines = code[start:].split("\n\n")[0].splitlines()
        lines = [line for line in lines if line.strip() != "variables = ctx.variables"]
    else:
        project.workflows.append(
            {
                "id": "flow",
                "name": "Example",
                "event": {"kind": "click", "component": "save_button"},
                "body": [node],
            }
        )
        code = generate(project).text
        lines = code[code.index("def ", code.index("# Example")) :].split("\n\n")[0].splitlines()
        lines = [line for line in lines[1:] if line.strip() and not line.strip().startswith("#")]
        lines = [line[4:] for line in lines if line.strip() != "variables = ctx.variables"]
        if not statement:
            lines = [re.sub(r"^ctx\.log\((.*)\)$", r"\1", lines[-1])]
    return "\n".join(lines)


def can(kind, build):
    """Whether the validator accepts this statement or expression on a component of `kind`."""
    project = Project.empty("Check")
    target = project.add(project.root.id, K.PAGES).children[0] if kind == K.PAGE else None
    if kind == K.WINDOW:
        return False
    if target is None:
        target = project.add(project.root.id, kind)
    project.metadata["logic_version"] = logic.LOGIC_VERSION
    project.metadata["collections"] = [
        {"id": "c", "name": "c", "fields": [{"id": "f", "name": "f", "type": "text"}]}
    ]
    project.workflows.append(
        {
            "id": "flow",
            "name": "check",
            "event": {"kind": "start", "component": project.root.id},
            "body": [numbered(build(target.id), [0])],
        }
    )
    try:
        logic.validate(project)
    except ProjectError:
        return False
    return True


def change_statement(op, component):
    if op == "set_chart":
        return {"op": op, "component": component, "labels": items(), "value": items()}
    if op in {"show_page"}:
        return {"op": op, "component": component}
    if op == "show_records":
        return {"op": op, "component": component, "collection": "c"}
    if op == "export_table":
        return {"op": op, "component": component, "path": lit("x.csv")}
    if op == "terminal_start":
        return {"op": op, "component": component, "program": lit(""), "arguments": items()}
    return {"op": op, "component": component, "value": lit("x")}


def components_page(language):
    t = PAGE_TEXT[language]
    pt = language != "en"
    lines = [GENERATED, "", f"# {t['components_title']}", "", t["components_intro"], ""]
    missing = set(K) - set(COMPONENTS)
    if missing:
        raise SystemExit(f"Describe these components in COMPONENTS: {sorted(missing)}")
    for kind in KIND_LABELS:
        en, ptext = COMPONENTS[kind]
        events = [e for e, kinds in logic.EVENT_TARGETS.items() if kind in kinds]
        reads = [a for a in READ if can(kind, lambda c, a=a: {"op": "log", "value": read(c, a)})]
        changes = [op for op in CHANGE if can(kind, lambda c, op=op: change_statement(op, c))]
        lines += [f"## {KIND_LABELS[kind]}", "", ptext if pt else en, ""]
        rows = [
            (t["events"], ", ".join(f"*{e}* ({EVENTS[e][1 if pt else 0]})" for e in events)),
            (t["read"], ", ".join(f'`"{a}"` ({READ[a][1 if pt else 0]})' for a in reads)),
            (t["change"], ", ".join(f"`{CHANGE[op]}`" for op in changes)),
        ]
        lines += ["| | |", "|---|---|"]
        lines += [f"| **{name}** | {value or t['none']} |" for name, value in rows]
        lines.append("")
    return "\n".join(lines)


def blocks_page(language):
    t = PAGE_TEXT[language]
    pt = language != "en"
    dictionary = pt_dictionary()
    source = LOGIC_JS.read_text()
    lines = [GENERATED, "", f"# {t['blocks_title']}", "", t["blocks_intro"], "", t["hats"], ""]
    listed = []
    for category, types in palette():
        lines += [f"## {dictionary.get(category, category) if pt else category}", ""]
        for block_type in types:
            if block_type not in BLOCKS:
                raise SystemExit(f"Describe the block {block_type} in BLOCKS")
            listed.append(block_type)
            label, en, ptext, sample = BLOCKS[block_type]
            if isinstance(label, tuple):
                shown = label[1] if pt else label[0]
            else:
                if f"'{label}'" not in source:
                    raise SystemExit(f"Label of {block_type} not found in logic.js: {label}")
                if pt and label not in dictionary and label != "Terminal":
                    raise SystemExit(
                        f"Label of {block_type} has no Portuguese in logic.js: {label}"
                    )
                shown = dictionary.get(label, label) if pt else label
            shown = re.sub(r"\s*%\d\s*", " … ", shown).strip()
            lines += [
                f"### {shown}",
                "",
                ptext if pt else en,
                "",
                f"*{t['generated']}:*",
                "",
                "```python",
                python_for(block_type, sample),
                "```",
                "",
            ]
    extra = set(BLOCKS) - set(listed)
    if extra:
        raise SystemExit(f"Blocks described but not in the palette: {sorted(extra)}")
    return "\n".join(lines)


def ctx_page(language):
    t = PAGE_TEXT[language]
    pt = language != "en"
    tree = ast.parse(STUB.read_text())
    lines = [GENERATED, "", f"# {t['ctx_title']}", "", t["ctx_intro"], ""]
    lines += [f"## {t['example']}", "", "```python", t["ctx_example"].rstrip(), "```", ""]
    classes = {n.name: n for n in tree.body if isinstance(n, ast.ClassDef)}
    for name, title in (("Context", "ctx"), ("Data", t["data_title"])):
        node = classes[name]
        doc = CTX_PT[name] if pt else ast.get_docstring(node)
        lines += [f"## {title}", "", doc, ""]
        members = node.body[1:]
        index = 0
        while index < len(members):
            member = members[index]
            index += 1
            if isinstance(member, ast.AnnAssign):
                key = member.target.id
                text = members[index].value.value if index < len(members) else ""
                index += 1
                signature = f"{key}: {ast.unparse(member.annotation)}"
            elif isinstance(member, ast.FunctionDef):
                key = member.name
                text = ast.get_docstring(member) or ""
                args = ast.unparse(member.args).replace("self, ", "").replace("self", "")
                prop = any(getattr(d, "id", "") == "property" for d in member.decorator_list)
                returns = ast.unparse(member.returns) if member.returns else "None"
                signature = f"{key}: {returns}" if prop else f"{key}({args}) -> {returns}"
            else:
                continue
            if key not in CTX_PT:
                raise SystemExit(f"Translate ctx member {key} in CTX_PT")
            prefix = "ctx." if name == "Context" else "ctx.data."
            lines += [
                f"### `{prefix}{key}`",
                "",
                "```python",
                prefix + signature,
                "```",
                "",
                CTX_PT[key] if pt else text,
                "",
            ]
    return "\n".join(lines)


