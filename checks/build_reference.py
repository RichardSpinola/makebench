def pt_dictionary():
    """The PT_BR dictionary of web/logic.js (its fourth line)."""
    line = next(x for x in LOGIC_JS.read_text().splitlines() if x.startswith("const PT_BR"))
    return json.loads(line[line.index("{") : line.rindex("}") + 1])


def palette():
    """Categories of the toolbox in order: (English name, [block types])."""
    text = LOGIC_JS.read_text()
    body = text[text.index("const toolbox") :]
    result = []
    for line in body.splitlines()[1:]:
        found = re.match(r"\s*\{kind:'category',name:(?:T\('([^']+)'\)|'([^']+)')", line)
        if not found:
            if line.startswith("]};"):
                break
            continue
        types = re.findall(r"block\('([a-z_]+)'|type:'([a-z_]+)'", line)
        result.append((found[1] or found[2], [a or b for a, b in types]))
    return result


