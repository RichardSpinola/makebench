"""Readable Python from the neutral model, never running project content."""

from dataclasses import dataclass, field
from .datamodel import find_collection, find_field
from .logic import (
    block_functions,
    editable,
    function_names,
    is_draft,
    is_python_event,
    suggest_function,
    validate,
)
from .project import Project, ProjectError
from makebench.i18n import tr


@dataclass
class GeneratedCode:
    """Code and line map (flow, block), with separate diagnostics."""

    text: str
    lines: dict[tuple[str, str], int] = field(default_factory=dict)
    diagnostics: list[str] = field(default_factory=list)


def generate(project: Project, source: str = "") -> GeneratedCode:
    """Generate handlers for the runtime ctx contract; does not export an application.

    The origin of each statement is kept in lines. No free-text field becomes Python
    without escaping: variable names are dict keys and values use repr.
    """
    validate(project)
    result = GeneratedCode("")
    lines = [
        "# " + tr("Generated by Makebench. Edit the logic to change this file."),
        "# " + tr("Your own functions live in the project's .actions.py file."),
        "# " + tr("Runs in a separate process when you test the application."),
        "",
    ]
    functions, syntax_error = function_names(source)
    if syntax_error:
        result.diagnostics.append(syntax_error)
    from .source import source_files, ENTRY_FILE
    import ast

    for filename, text in source_files(source).items():
        if filename != ENTRY_FILE:
            try:
                ast.parse(text)
            except (SyntaxError, ValueError) as exc:
                result.diagnostics.append(filename + ": " + str(exc))
    if not editable(project):
        result.diagnostics.append(
            tr("Reserved flows from another version were kept without conversion.")
        )
    else:
        blocks_defined = {item["id"]: item for item in block_functions(project)}
        units = [(None, item) for item in blocks_defined.values()]
        for index, flow in [*units, *enumerate(project.workflows, 1)]:
            flow_id = flow["id"]
            if "function" in flow:
                lines.extend(
                    [
                        f"# {flow['name'].replace(chr(10), ' ').replace(chr(13), ' ')}",
                        f"def on_event_{index}(ctx):",
                        f"    ctx.handle_event({flow['function']!r})",
                        "",
                    ]
                )
                continue
            if flow.get("body") is None:
                result.diagnostics.extend(
                    f"{flow['name']}: {e}"
                    for e in (flow.get("errors") or [tr("Complete the blocks.")])
                )
                continue

            def expression(node):
                """Turn a validated expression into escaped Python text."""
                op = node["op"]
                if op == "literal":
                    return repr(node["value"])
                if op == "list":
                    return "[" + ", ".join(expression(item) for item in node["items"]) + "]"
                if op == "variable":
                    return f"{ {'project': 'variables', 'window': 'ctx.window_variables', 'local': 'local_variables'}[node.get('scope', 'project')] }.get({node['name']!r})"
                if op == "read":
                    return f"ctx.read({node['component']!r}, {node['attribute']!r})"
                if op == "call_function":
                    return call(node)
                if op in {"file_text", "csv_rows"}:
                    method = "read_text" if op == "file_text" else "read_csv"
                    return f"ctx.{method}({expression(node['path'])})"
                if op.startswith("data_") or op == "record_field":
                    return data_expression(node)
                left, right = expression(node["left"]), expression(node["right"])
                if op == "join":
                    return f"(str({left}) + str({right}))"
                return f"({left} {node['operator']} {right})"

            def data_name(node, key="field"):
                """Collection and field names as the user declared them."""
                owner = find_collection(project.metadata, node["collection"])
                found = find_field(owner, node[key]) if node.get(key) not in {None, "id"} else None
                return owner["name"], found["name"] if found else node.get(key)

            def data_filter(node):
                """The optional filter arguments of a query, as Python text."""
                if node.get("field") is None:
                    return ""
                _, field = data_name(node)
                return f", {field!r}, {node.get('operator', '=')!r}, {expression(node['value'])}"

            def data_expression(node):
                """Python for the expression blocks of the Data category."""
                op = node["op"]
                if op == "data_last_id":
                    return "ctx.data.last_id"
                if op == "record_field":
                    _, field = data_name(node)
                    return f"({expression(node['record'])} or {{}}).get({field!r})"
                name = data_name(node, "order")[0]
                if op in {"data_get", "data_name"}:
                    method = "get" if op == "data_get" else "name"
                    return f"ctx.data.{method}({name!r}, {expression(node['record_id'])})"
                if op == "data_count":
                    return f"ctx.data.count({name!r}{data_filter(node)})"
                if op == "data_sum":
                    summed = data_name(node, "sum")[1]
                    if node.get("field") is None:
                        return f"ctx.data.sum({name!r}, {summed!r})"
                    _, field = data_name(node)
                    return (
                        f"ctx.data.sum({name!r}, {summed!r}, {field!r}, "
                        f"{node.get('operator', '=')!r}, {expression(node['value'])})"
                    )
                order = ""
                if node.get("order") is not None:
                    order = f", order={data_name(node, 'order')[1]!r}"
                    if node.get("descending"):
                        order += ", descending=True"
                if node.get("field") is None and not order:
                    return f"ctx.data.find({name!r})"
                if node.get("field") is None:
                    return f"ctx.data.find({name!r}{order})"
                return f"ctx.data.find({name!r}{data_filter(node)}{order})"

            def data_values(node):
                """Keyword arguments for the fields an add or change block fills in."""
                return "".join(
                    f", {data_name({'collection': node['collection'], 'field': entry['field']})[1]}="
                    f"{expression(entry['value'])}"
                    for entry in node["values"]
                )

            def call(node):
                """Call a block function by its generated name, inputs in order."""
                target = blocks_defined[node["function"]]
                args = "".join(", " + expression(item) for item in node["args"])
                return f"fn_{target['name']}(ctx{args})"

            def emit(text, node=None, indent=1):
                """Append a line and record where the statement's expressions came from."""
                if node:

                    def mark(value):
                        """Map the statement and its values to the same Python line."""
                        if isinstance(value, dict) and "op" in value:
                            result.lines[(flow_id, value["id"])] = len(lines) + 1
                            for key, child in value.items():
                                if key not in {"then", "else", "body"}:
                                    mark(child)
                        elif isinstance(value, list):
                            for child in value:
                                mark(child)

                    mark(node)
                lines.append("    " * indent + text)

            def body(items, indent=1):
                """Translate the sequence keeping order, conditions and comments."""
                if not items:
                    emit("pass", indent=indent)
                for node in items:
                    for comment in node.get("comment", "").splitlines():
                        emit("# " + comment, indent=indent)
                    op = node["op"]
                    if op in {"log", "message"}:
                        emit(f"ctx.{op}({expression(node['value'])})", node, indent)
                    elif op.startswith("set_") or op == "add_row":
                        emit(
                            f"ctx.{op}({node['component']!r}, {expression(node['value'])})",
                            node,
                            indent,
                        )
                    elif op == "terminal_start":
                        emit(
                            f"ctx.terminal_start({node['component']!r}, {expression(node['program'])}, {expression(node['arguments'])})",
                            node,
                            indent,
                        )
                    elif op == "terminal_send":
                        emit(
                            f"ctx.terminal_send({node['component']!r}, {expression(node['value'])})",
                            node,
                            indent,
                        )
                    elif op == "terminal_stop":
                        emit(f"ctx.terminal_stop({node['component']!r})", node, indent)
                    elif op == "show_page":
                        emit(f"ctx.show_page({node['component']!r})", node, indent)
                    elif op == "go_state":
                        emit(f"ctx.go_state({node['state']!r})", node, indent)
                    elif op == "open_window":
                        emit(
                            f"ctx.open_window({node['window']!r}, close_current={node.get('close_current', False)!r})",
                            node,
                            indent,
                        )
                    elif op == "close_window":
                        emit("ctx.close_window()", node, indent)
                    elif op == "assign":
                        emit(
                            f"{ {'project': 'variables', 'window': 'ctx.window_variables', 'local': 'local_variables'}[node.get('scope', 'project')] }[{node['name']!r}] = {expression(node['value'])}",
                            node,
                            indent,
                        )
                    elif op == "call":
                        if node["function"] not in functions:
                            result.diagnostics.append(
                                tr(
                                    "{flow}: function ‘{function}’ not found in .actions.py."
                                ).format(flow=flow["name"], function=node["function"])
                            )
                        emit(
                            f"ctx.call_action({node['function']!r}, {expression(node['value'])})",
                            node,
                            indent,
                        )
                    elif op in {"run", "script"}:
                        method, key = (
                            ("run", "program") if op == "run" else ("run_script", "source")
                        )
                        emit(
                            f"ctx.{method}({expression(node[key])}, {expression(node['arguments'])}, admin={node['admin']!r})",
                            node,
                            indent,
                        )
                    elif op == "ask":
                        emit(
                            f"{ {'project': 'variables', 'window': 'ctx.window_variables', 'local': 'local_variables'}[node.get('scope', 'project')] }[{node['name']!r}] = ctx.ask({node['kind']!r}, {expression(node['prompt'])}, {expression(node['options'])})",
                            node,
                            indent,
                        )
                    elif op == "confirm":
                        emit(f"ctx.confirm({expression(node['prompt'])})", node, indent)
                    elif op == "call_function":
                        emit(call(node), node, indent)
                    elif op == "return":
                        value = expression(node["value"]) if "value" in node else "None"
                        emit(f"return {value}", node, indent)
                    elif op == "if":
                        emit(f"if {expression(node['condition'])}:", node, indent)
                        body(node["then"], indent + 1)
                        if node["else"]:
                            emit("else:", indent=indent)
                            body(node["else"], indent + 1)
                    elif op == "for_each":
                        emit(f"for _item in ({expression(node['source'])} or []):", node, indent)
                        emit(f"local_variables[{node['name']!r}] = _item", indent=indent + 1)
                        body(node["body"], indent + 1)
                    elif op == "data_add":
                        emit(
                            f"ctx.data.add({data_name(node, 'x')[0]!r}{data_values(node)})",
                            node,
                            indent,
                        )
                    elif op == "data_update":
                        emit(
                            f"ctx.data.update({data_name(node, 'x')[0]!r}, {expression(node['record_id'])}{data_values(node)})",
                            node,
                            indent,
                        )
                    elif op == "write_file":
                        emit(
                            f"ctx.write_text({expression(node['path'])}, {expression(node['value'])})",
                            node,
                            indent,
                        )
                    elif op == "export_table":
                        emit(
                            f"ctx.export_table_csv({expression(node['path'])}, {node['component']!r})",
                            node,
                            indent,
                        )
                    elif op == "export_records":
                        records = f", {expression(node['records'])}" if "records" in node else ""
                        emit(
                            f"ctx.export_records_csv({expression(node['path'])}, {data_name(node, 'x')[0]!r}{records})",
                            node,
                            indent,
                        )
                    elif op == "show_records":
                        records = f", {expression(node['records'])}" if "records" in node else ""
                        emit(
                            f"ctx.show_records({node['component']!r}, {data_name(node, 'x')[0]!r}{records})",
                            node,
                            indent,
                        )
                    elif op == "data_delete":
                        emit(
                            f"ctx.data.delete({data_name(node, 'x')[0]!r}, {expression(node['record_id'])})",
                            node,
                            indent,
                        )
                    elif op == "repeat":
                        emit(
                            f"for _ in range(max(0, int({expression(node['count'])}))):",
                            node,
                            indent,
                        )
                        body(node["body"], indent + 1)

            if index is None:
                params = flow["params"]
                lines.extend(
                    [
                        "# " + tr("Function: {name}").format(name=flow["name"]),
                        f"def fn_{flow['name']}({', '.join(['ctx', *params])}):",
                        "    variables = ctx.variables",
                        "    local_variables = {"
                        + ", ".join(f"{name!r}: {name}" for name in params)
                        + "}",
                    ]
                )
                body(flow["body"])
                lines.append("")
                continue
            lines.extend(
                [
                    f"# {flow['name'].replace(chr(10), ' ').replace(chr(13), ' ')}",
                    "# "
                    + tr("Event: {kind} on {component}").format(
                        kind=flow["event"]["kind"], component=repr(flow["event"]["component"])
                    ),
                    f"def on_event_{index}(ctx):",
                    "    variables = ctx.variables",
                ]
            )

            def uses_local(value):
                """Detect local data by structure, never inspecting literal text."""
                if isinstance(value, dict):
                    return value.get("scope") == "local" or any(
                        uses_local(v) for v in value.values()
                    )
                if isinstance(value, list):
                    return any(uses_local(v) for v in value)
                return False

            if uses_local(flow["body"]):
                emit("local_variables = {}")
            body(flow["body"])
            lines.append("")
    result.text = "\n".join(lines) + "\n"
    return result


def convert_to_python(project: Project, source: str) -> str:
    """Turn every blocks flow into a function of the actions file; returns the new source.

    The project changes in place: flows keep their id, name, event and states and
    point to the new function. Drafts must be finished first.
    """
    if not editable(project):
        raise ProjectError(tr("Reserved flows from another version cannot be converted."))
    functions = block_functions(project)
    drafts = [flow["name"] for flow in [*functions, *project.workflows] if is_draft(flow)]
    if drafts:
        raise ProjectError(
            tr("Finish these flows before converting: {names}.").format(names=", ".join(drafts))
        )
    names, error = function_names(source)
    if error:
        raise ProjectError(tr("Fix the Python file before converting. {error}").format(error=error))
    generated = generate(project, source).text.splitlines()
    taken, chunks = set(names), []
    clashes = [f"fn_{item['name']}" for item in functions if f"fn_{item['name']}" in taken]
    if clashes:
        raise ProjectError(
            tr("The Python file already defines {names}. Rename them first.").format(
                names=", ".join(clashes)
            )
        )

    def chunk_at(header):
        """Cut a generated definition with the comments right above it."""
        start = next(i for i, line in enumerate(generated) if line.startswith(header))
        head, end = start, start
        while head > 0 and generated[head - 1].startswith("#"):
            head -= 1
        while end < len(generated) and generated[end]:
            end += 1
        return start - head, generated[head:end]

    for item in functions:
        taken.add(f"fn_{item['name']}")
        chunks.append("\n".join(chunk_at(f"def fn_{item['name']}(")[1]))
    for index, flow in enumerate(project.workflows, 1):
        if is_python_event(flow):
            continue
        offset, chunk = chunk_at(f"def on_event_{index}(ctx):")
        name = suggest_function(project, flow["event"]["component"], taken, flow["event"]["kind"])
        taken.add(name)
        chunk[offset] = f"def {name}(ctx):"
        chunks.append("\n".join(chunk))
        kept = {key: flow[key] for key in ("id", "name", "event", "states") if key in flow}
        flow.clear()
        flow.update(kept, function=name)
    project.metadata.pop("functions", None)
    project.metadata["programming"] = "python"
    text = source.rstrip("\n")
    if not chunks:
        return source
    return (text + "\n\n\n" if text else "") + "\n\n\n".join(chunks) + "\n"
